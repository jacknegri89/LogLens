import type { Severity } from '../../types/report';
import { FAILURE_LINE, FALLBACK_RULE, type Rule } from '../../content/rules';
import type { AIProvider, AnalyzeInput } from '../AIProvider';
import { buildFindings } from '../findings';
import { makeTitle, pickRule, pickSeverity } from '../ruleMatching';
import { aiReportSchema, type AIReport } from '../schema';

const MAX_KEY_LINES = 6;

/** True when a known failure matches the text, so the rules can explain it without a model. */
export function hasKnownRule(text: string): boolean {
  return pickRule(text) !== FALLBACK_RULE;
}

function pickKeyLines(lines: string[], rule: Rule): string[] {
  const matching = lines.filter((line) => rule.pattern.test(line) || FAILURE_LINE.test(line));
  const chosen = matching.length > 0 ? matching : lines;
  return [...new Set(chosen)].slice(0, MAX_KEY_LINES);
}

interface IssueFields {
  title: string;
  severity: Severity;
  category: string;
  keyLines: string[];
  causes: string[];
  debugSteps: string[];
}

function buildIssue(issue: IssueFields): string {
  const fence = codeFence(issue.keyLines);
  return [
    `## ${issue.title}`,
    '',
    `**Severity:** ${issue.severity}`,
    `**Category:** ${issue.category}`,
    '',
    '### Log lines',
    '',
    fence,
    ...issue.keyLines,
    fence,
    '',
    ...causesSection(issue.causes),
    ...stepsSection(issue.debugSteps),
    '_Report generated by the LogLens rules engine._',
  ].join('\n');
}

/** A code fence longer than any run of backticks in the lines, so a log line cannot close it. */
function codeFence(lines: string[]): string {
  const longestRun = Math.max(
    0,
    ...lines.flatMap((line) => line.match(/`+/g) ?? []).map((run) => run.length),
  );
  return '`'.repeat(Math.max(3, longestRun + 1));
}

function causesSection(causes: string[]): string[] {
  return ['### Probable causes', '', ...causes.map((cause) => `- ${cause}`), ''];
}

function stepsSection(debugSteps: string[]): string[] {
  return [
    '### Suggested next steps',
    '',
    ...debugSteps.map((step, index) => `${index + 1}. ${step}`),
    '',
  ];
}

function buildReport({ excerpt, severityHint }: AnalyzeInput): AIReport {
  const lines = excerpt.split('\n').filter((line) => line.trim() !== '');
  const rule = pickRule(excerpt);
  const keyLines = pickKeyLines(lines, rule);
  const issue: IssueFields = {
    title: makeTitle(keyLines),
    severity: pickSeverity(rule, excerpt, severityHint),
    category: rule.category,
    keyLines,
    causes: rule.causesFor ? rule.causesFor(excerpt) : rule.causes,
    debugSteps: rule.debugSteps,
  };
  const findings = buildFindings(excerpt, severityHint);

  return aiReportSchema.parse({
    ...issue,
    bugReportMarkdown: buildIssue(issue),
    ...(findings.length > 0 ? { findings } : {}),
  });
}

/**
 * Analyses a log with a table of known failures instead of calling a model.
 * It needs no key and no network, and the same log always gives the same
 * report. It recognises common problems; for anything else it says so.
 */
export class RulesProvider implements AIProvider {
  readonly name = 'rules';

  analyze(input: AnalyzeInput): Promise<AIReport> {
    return Promise.resolve(buildReport(input));
  }
}
