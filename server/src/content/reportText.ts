/**
 * The fixed words around a rules-engine report: the headings of the issue text and the titles
 * built when a log line has none of its own. English here, other languages in `reportText.<code>.ts`.
 */
export interface ReportText {
  severity: string;
  category: string;
  logLines: string;
  bigPicture: string;
  probableCauses: string;
  nextSteps: string;
  generatedByRules: string;
  /** Title of an access-log line: "GET /api/users returned 500". */
  requestTitle: (method: string, path: string, status: string) => string;
  unknownIssue: string;
}

export const REPORT_TEXT: ReportText = {
  severity: 'Severity',
  category: 'Category',
  logLines: 'Log lines',
  bigPicture: 'Big picture',
  probableCauses: 'Probable causes',
  nextSteps: 'Suggested next steps',
  generatedByRules: 'Report generated by the LogLens rules engine.',
  requestTitle: (method, path, status) => `${method} ${path} returned ${status}`,
  unknownIssue: 'Unknown issue',
};
